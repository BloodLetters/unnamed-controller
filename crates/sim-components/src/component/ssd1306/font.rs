/// Renders a text string into display GDDRAM at the specified coordinates.
pub fn draw_text_on_display(ssd: &mut super::Ssd1306, mut x: usize, mut y: usize, text: &str) {
    for ch in text.chars() {
        if ch == '\n' {
            y = (y + 8) % super::SSD1306_HEIGHT;
            x = 0;
            continue;
        }
        if x + 6 > super::SSD1306_WIDTH {
            y = (y + 8) % super::SSD1306_HEIGHT;
            x = 0;
        }
        let glyph = get_glyph(ch);
        for (cx, &col_byte) in glyph.iter().enumerate() {
            for cy in 0..8 {
                if (col_byte & (1 << cy)) != 0 {
                    ssd.set_pixel(x + cx, y + cy, true);
                }
            }
        }
        x += 6;
    }
}
